import { useCallback, useState } from 'react';
import {
  Check,
  Copy,
  Download,
  FileText,
  Link as LinkIcon,
  MessageCircle,
  Share2,
  Star,
} from 'lucide-react';
import StarRating from '@/components/StarRating';
import type { FeedbackResponseRow } from '@/types/database';

type PdfReportData = {
  className: string;
  usthadName: string;
  subjectName: string;
  responses: FeedbackResponseRow[];
  avgRating: number;
  limit: number;
  responseCount: number;
  institutionName: string;
  requireStudentName: boolean;
};

export default function PdfReport({ data }: { data: PdfReportData }) {
  const [whatsappNumber, setWhatsappNumber] = useState('');
  const [copied, setCopied] = useState(false);

  const ratingDist = [5, 4, 3, 2, 1].map((star) => ({
    star,
    count: data.responses.filter((r) => r.rating === star).length,
  }));

  const handleDownload = useCallback(() => {
    window.print();
  }, []);

  const handleWhatsAppShare = useCallback(() => {
    const number = whatsappNumber.replace(/[^0-9]/g, '');
    if (!number) return;
    const message = `Feedback Report
Class: ${data.className}
Usthad: ${data.usthadName}
Subject: ${data.subjectName}
Responses: ${data.responseCount}/${data.limit}
Average Rating: ${data.avgRating.toFixed(1)}/5

Generated by Malik Deenar Islamic Academy`;

    const url = `https://wa.me/${number}?text=${encodeURIComponent(message)}`;
    window.open(url, '_blank');
  }, [whatsappNumber, data]);

  const handleNativeShare = useCallback(async () => {
    const message = `Feedback Report
Class: ${data.className}
Usthad: ${data.usthadName}
Subject: ${data.subjectName}
Responses: ${data.responseCount}/${data.limit}
Average Rating: ${data.avgRating.toFixed(1)}/5`;

    if (navigator.share) {
      try {
        await navigator.share({
          title: 'Feedback Report',
          text: message,
        });
      } catch {
        // user cancelled
      }
    } else {
      navigator.clipboard.writeText(message);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  }, [data]);

  const handleCopyLink = useCallback(() => {
    const reportText = `Feedback Report
Class: ${data.className}
Usthad: ${data.usthadName}
Subject: ${data.subjectName}
Responses: ${data.responseCount}/${data.limit}
Average Rating: ${data.avgRating.toFixed(1)}/5`;
    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  }, [data]);

  return (
    <div>
      {/* A4-style report content */}
      <div className="mx-auto max-w-2xl rounded-xl border border-slate-200 bg-white p-8 print:shadow-none">
        {/* Header */}
        <div className="mb-6 flex items-center justify-between border-b-2 border-slate-800 pb-4">
          <div className="flex items-center gap-3">
            <div className="flex h-12 w-12 items-center justify-center rounded-xl bg-blue-600">
              <FileText className="h-6 w-6 text-white" />
            </div>
            <div>
              <h2 className="text-lg font-bold text-slate-900">
                {data.institutionName}
              </h2>
              <p className="text-xs text-slate-500">
                Feedback Report
              </p>
            </div>
          </div>
          <div className="text-right text-xs text-slate-500">
            <p>Date: {new Date().toLocaleDateString('en-GB')}</p>
          </div>
        </div>

        {/* Info */}
        <div className="mb-6 grid grid-cols-1 gap-3 sm:grid-cols-3">
          <div className="rounded-lg bg-slate-50 p-3">
            <p className="text-xs font-semibold uppercase text-slate-400">
              Class
            </p>
            <p className="mt-1 text-sm font-bold text-slate-800">
              {data.className}
            </p>
          </div>
          <div className="rounded-lg bg-slate-50 p-3">
            <p className="text-xs font-semibold uppercase text-slate-400">
              Usthad
            </p>
            <p className="mt-1 text-sm font-bold text-slate-800">
              {data.usthadName}
            </p>
          </div>
          <div className="rounded-lg bg-slate-50 p-3">
            <p className="text-xs font-semibold uppercase text-slate-400">
              Subject
            </p>
            <p className="mt-1 text-sm font-bold text-slate-800">
              {data.subjectName}
            </p>
          </div>
        </div>

        {/* Overall rating */}
        <div className="mb-6 rounded-xl border border-slate-200 p-4 text-center">
          <p className="mb-2 text-sm font-semibold text-slate-600">
            Overall Rating
          </p>
          <div className="flex items-center justify-center gap-2">
            <StarRating
              value={Math.round(data.avgRating)}
              readOnly
              size={28}
            />
          </div>
          <p className="mt-2 text-2xl font-bold text-slate-900">
            {data.avgRating.toFixed(1)} / 5
          </p>
          <p className="mt-1 text-xs text-slate-500">
            Responses: {data.responseCount} / {data.limit}
          </p>
        </div>

        {/* Rating distribution */}
        <div className="mb-6">
          <h3 className="mb-3 text-sm font-bold text-slate-800">
            Rating Distribution
          </h3>
          <div className="space-y-2">
            {ratingDist.map((rd) => (
              <div key={rd.star} className="flex items-center gap-3 text-sm">
                <span className="flex w-16 items-center gap-1 text-slate-600">
                  {rd.star} <Star className="h-3 w-3 fill-amber-400 text-amber-400" />
                </span>
                <div className="h-3 flex-1 overflow-hidden rounded-full bg-slate-100">
                  <div
                    className="h-full rounded-full bg-amber-400 transition-all"
                    style={{
                      width: `${
                        data.responses.length > 0
                          ? (rd.count / data.responses.length) * 100
                          : 0
                      }%`,
                    }}
                  />
                </div>
                <span className="w-8 text-right font-medium text-slate-700">
                  {rd.count}
                </span>
              </div>
            ))}
          </div>
        </div>

        {/* Written feedback */}
        {data.responses.some((r) => r.comment) && (
          <div className="mb-6">
            <h3 className="mb-3 text-sm font-bold text-slate-800">
              Written Feedback
            </h3>
            <div className="space-y-3">
              {data.responses
                .filter((r) => r.comment)
                .map((r, i) => (
                  <div
                    key={r.id}
                    className="break-inside-avoid rounded-lg border border-slate-100 p-3"
                    style={{ pageBreakInside: 'avoid' }}
                  >
                    <div className="flex flex-nowrap items-center justify-between gap-3">
                      <StarRating value={r.rating} readOnly size={14} />
                      <span className="text-xs text-slate-400">
                        #{i + 1}
                      </span>
                    </div>
                    <p className="mt-1.5 whitespace-pre-wrap break-words text-sm italic text-slate-600">
                      "{r.comment}"
                    </p>
                    {data.requireStudentName && r.student_name && (
                      <p className="mt-1 text-xs text-slate-400">
                        — {r.student_name}
                      </p>
                    )}
                    {r.student_number && (
                      <p className="mt-1 text-xs text-slate-400">
                        Student {r.student_number}
                      </p>
                    )}
                  </div>
                ))}
            </div>
          </div>
        )}

        {/* Footer */}
        <div className="border-t border-slate-200 pt-4 text-center">
          <p className="text-xs text-slate-400">
            Generated by Malik Deenar Islamic Academy
          </p>
        </div>
      </div>

      {/* Share actions (hidden when printing) */}
      <div className="mt-6 space-y-4 print:hidden">
        <div className="flex flex-wrap gap-3">
          <button
            onClick={handleDownload}
            className="flex items-center gap-2 rounded-xl bg-blue-600 px-5 py-3 text-sm font-semibold text-white transition hover:bg-blue-700"
          >
            <Download className="h-4 w-4" />
            Download PDF
          </button>
          <button
            onClick={handleNativeShare}
            className="flex items-center gap-2 rounded-xl bg-slate-100 px-5 py-3 text-sm font-semibold text-slate-700 transition hover:bg-slate-200"
          >
            <Share2 className="h-4 w-4" />
            Share
          </button>
          <button
            onClick={handleCopyLink}
            className="flex items-center gap-2 rounded-xl bg-slate-100 px-5 py-3 text-sm font-semibold text-slate-700 transition hover:bg-slate-200"
          >
            {copied ? (
              <>
                <Check className="h-4 w-4 text-green-600" />
                Copied!
              </>
            ) : (
              <>
                <LinkIcon className="h-4 w-4" />
                Copy Report
              </>
            )}
          </button>
        </div>

        {/* WhatsApp */}
        <div className="rounded-xl border border-green-200 bg-green-50 p-4">
          <p className="mb-3 text-sm font-semibold text-green-800">
            Share via WhatsApp
          </p>
          <div className="flex flex-wrap items-center gap-2">
            <input
              type="tel"
              value={whatsappNumber}
              onChange={(e) => setWhatsappNumber(e.target.value)}
              placeholder="+91 XXXXXXXXXX"
              className="flex-1 rounded-lg border border-green-300 bg-white px-4 py-2.5 text-sm outline-none transition focus:border-green-500"
            />
            <button
              onClick={handleWhatsAppShare}
              disabled={!whatsappNumber.trim()}
              className="flex items-center gap-2 rounded-lg bg-green-600 px-5 py-2.5 text-sm font-semibold text-white transition hover:bg-green-700 disabled:opacity-50"
            >
              <MessageCircle className="h-4 w-4" />
              Share Report
            </button>
          </div>
          <p className="mt-2 text-xs text-green-700">
            Opens WhatsApp with a prepared message. The PDF can be shared
            separately via the Share button or downloaded and attached manually.
          </p>
        </div>
      </div>
    </div>
  );
}
